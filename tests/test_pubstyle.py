# ---------------------------------------------------------------- tiny harness

_results = []


def test(fn):
    try:
        fn()
        _results.append((fn.__name__, None))
        print(f"PASS: {fn.__name__}")
    except Exception:
        _results.append((fn.__name__, traceback.format_exc()))
        print(f"FAIL: {fn.__name__}\n{traceback.format_exc()}")
    return fn


def raises(exc, fn, *args, match=None, **kw):
    try:
        fn(*args, **kw)
    except exc as e:
        if match is not None:
            assert re.search(match, str(e)), f"error text {str(e)!r} does not match {match!r}"
        return e
    raise AssertionError(f"{getattr(fn, '__name__', fn)} did not raise {exc.__name__}")


def no_fail(checks):
    bad = [c for c in checks if c.startswith("FAIL")]
    assert not bad, "unexpected FAIL: " + " | ".join(bad)


# ---------------------------------------------------------------- synthetic VASP files

def make_vasp_files(out: Path, metal: bool = False, eigenval: bool = True) -> Path:
    """Simple cubic toy cell (a = 5 A, Li + Cl), path G-X-M-G, 4 bands (2 occupied),
    DOSCAR with LORBIT = 11 columns. metal=True drops the third band below the VBM."""
    out.mkdir(parents=True, exist_ok=True)
    (out / "POSCAR").write_text(
        "LiCl toy\n1.0\n5.0 0.0 0.0\n0.0 5.0 0.0\n0.0 0.0 5.0\nLi Cl\n1 1\nDirect\n"
        "0.0 0.0 0.0\n0.5 0.5 0.5\n")
    G, X, M = np.array([0, 0, 0.]), np.array([.5, 0, 0]), np.array([.5, .5, 0])
    pts = np.array([a + (b - a) * t for a, b in ((G, X), (X, M), (M, G))
                    for t in np.linspace(0, 1, 6)])
    nk, nb, nelect = len(pts), 4, 4

    def bands(k):
        c = np.cos(2 * np.pi * k).sum()
        third = (-2.5 if metal else 2.0) + 0.3 * (3 - c) / 3
        return np.array([-3 - 0.4 * c, -1 - 0.3 * c, third, 4 + 0.2 * c])

    if eigenval:
        lines = ["   2   2   1   1", "  0.1E+02 0.1E-09 0.1E-09 0.1E-09 0.5E-15", "  1.0E-04",
                 "  CAR", " toy", f"   {nelect}  {nk}  {nb}"]
        for k in pts:
            lines += ["", f"  {k[0]:.8E} {k[1]:.8E} {k[2]:.8E}  {1.0 / nk:.8E}"]
            for i, e in enumerate(bands(k), 1):
                lines.append(f"   {i}   {e:.6f}   {1.0 if i <= nelect // 2 else 0.0:.6f}")
        (out / "EIGENVAL").write_text("\n".join(lines) + "\n")
    kp = ["K-Path Generated by VASPKIT.", "   6", "Line-Mode", "Reciprocal"]
    for (a, la), (b, lb) in (((G, "GAMMA"), (X, "X")), ((X, "X"), (M, "M")), ((M, "M"), (G, "GAMMA"))):
        kp += [f"  {a[0]:.6f} {a[1]:.6f} {a[2]:.6f} {la}", f"  {b[0]:.6f} {b[1]:.6f} {b[2]:.6f} {lb}", ""]
    (out / "KPATH.in").write_text("\n".join(kp) + "\n")

    nedos = 300
    e = np.linspace(-8, 8, nedos)
    g = lambda x, c, w, a: a * np.exp(-((x - c) / w) ** 2)  # noqa: E731
    dli = g(e, -1, .6, 1.0) + g(e, 4.5, .8, .6)
    dcl = g(e, -3, .5, 2.0) + g(e, 3.5, .7, .3)
    dl = ["   2   2   1   0", "  1 1 1 1 1", "  1.0", "  1.0", "  CAR", f"  8.0 -8.0 {nedos} 0.5 1.0"]
    dl += [f"{x:.4f} {t:.6f} 0.000000" for x, t in zip(e, dli + dcl)]
    for d in (dli, dcl):
        dl.append(f"  8.0 -8.0 {nedos} 0.5 1.0")
        for x, v in zip(e, d):
            cols = [v * 0.5, 0, 0, v * 0.1, 0, 0, 0, 0, 0]
            dl.append(f"{x:.4f} " + " ".join(f"{c:.6f}" for c in cols))
    (out / "DOSCAR").write_text("\n".join(dl) + "\n")
    return out


def fresh_registry():
    return ps.ColorRegistry(Path(tempfile.mkdtemp(dir=TMP)) / "colors.json")


# ---------------------------------------------------------------- bands

@test
def bands_insulator_read_and_plot():
    d = make_vasp_files(TMP / "ins")
    b = ps.read_bands(d)
    assert not b.metal and abs(b.gap - 2.7) < 1e-6, b.gap
    assert b.direct is False                          # VBM at M, CBM at Gamma in the toy
    assert b.labels[0] == r"$\rm\Gamma$" and b.labels[-1] == r"$\rm\Gamma$", b.labels
    assert all(np.diff(b.ticks) > 0)
    fig, ax = ps.new_figure("tall")
    ps.plot_bands(ax, b)
    no_fail(ps.save(fig, "bands", TMP / "out_bands"))
    assert "indirect" in ps.bands_summary(b)


@test
def bands_metal_needs_outcar_then_works():
    d = make_vasp_files(TMP / "met", metal=True)
    raises(ValueError, ps.read_bands, d, match="OUTCAR")
    (d / "OUTCAR").write_text(" E-fermi :  -1.2345     XC(G=0):  -9.0\n")
    b = ps.read_bands(d)
    assert b.metal and abs(b.zero_eV + 1.2345) < 1e-9
    fig, ax = ps.new_figure("tall")
    ps.plot_bands(ax, b)
    no_fail(ps.save(fig, "bands_metal", TMP / "out_bands"))


# ---------------------------------------------------------------- DOS

@test
def dos_insulator_read_and_plot():
    d = make_vasp_files(TMP / "ins")
    raises(ValueError, ps.read_dos, d, match="formula_units")
    dos = ps.read_dos(d, formula_units=1)
    assert not dos.metal and abs(dos.gap - 2.7) < 1e-6 and list(dos.elements) == ["Li", "Cl"]
    reg = fresh_registry()
    for kind in ("elements", "total", {"Li": ["s"], "Cl": ["p"]}):
        fig, ax = ps.new_figure()
        ps.plot_dos(ax, dos, reg, kind=kind)
        ps.place_legend(ax)
        no_fail(ps.save(fig, f"dos_{'x' if isinstance(kind, dict) else kind}", TMP / "out_dos"))
    assert "Gap: 2.700" in ps.dos_summary(dos)


@test
def dos_without_eigenval_stops_instead_of_guessing():
    d = make_vasp_files(TMP / "noeig", eigenval=False)
    raises(FileNotFoundError, ps.read_dos, d, formula_units=1, match="EIGENVAL")
    dos = ps.read_dos(d, formula_units=1, assume_metal=True)      # explicit opt-in
    assert dos.metal and dos.gap is None
    assert "Metal" in ps.dos_summary(dos)


@test
def dos_bad_requests_give_clear_errors():
    dos = ps.read_dos(make_vasp_files(TMP / "ins"), formula_units=1)
    reg = fresh_registry()
    fig, ax = ps.new_figure()
    raises(ValueError, ps.plot_dos, ax, dos, reg, kind="total", total=False, match="nothing to draw")
    raises(ValueError, ps.plot_dos, ax, dos, reg, xlim=(50, 60), match="no DOS points")
    ps.plt.close(fig)


# ---------------------------------------------------------------- INCAR

@test
def incar_parsing():
    f = TMP / "INCAR"
    f.write_text("SYSTEM = x\nLCLIMB = .TRUE.   ! climbing image\nICHAIN = 0\n")
    assert ps.incar_true(f, "LCLIMB") is True
    f.write_text("ICHAIN = 0 ; LCLIMB = .TRUE.\n")               # several tags on one line
    assert ps.incar_true(f, "LCLIMB") is True and ps.incar_value(f, "ICHAIN") == "0"
    f.write_text("LCLIMB = .FALSE.\n")
    assert ps.incar_true(f, "LCLIMB") is False
    f.write_text("# LCLIMB = .TRUE.\nICHAIN = 0\n")              # commented out = absent
    assert ps.incar_value(f, "LCLIMB") is None
    raises(ValueError, ps.incar_true, f, "LCLIMB", match="not set")
    assert ps.incar_true(f, "LCLIMB", default=True) is True
    assert ps.incar_true(f, "LCLIMB", default=False) is False


# ---------------------------------------------------------------- limits and fills

@test
def nice_limits_normal_and_edge_cases():
    fig, ax = ps.new_figure()
    assert ps.nice_limits(ax, 50) == (0.0, 60.0, 20.0)           # the example in SKILL.md
    raises(ValueError, ps.nice_limits, ax, 0.0, match="nothing above zero")
    raises(ValueError, ps.nice_limits, ax, -2.0, match="nothing above zero")
    raises(ValueError, ps.nice_limits, ax, float("nan"), match="not finite")
    lo, hi, _ = ps.nice_limits(ax, 1.0, data_min=1.0, start_at_zero=False)   # flat data
    assert lo < 1.0 < hi
    lo, hi, _ = ps.nice_limits(ax, 1.0, data_min=1.0, start_at_zero=False, headroom=0.0)
    assert lo < 1.0 < hi
    ps.plt.close(fig)


@test
def gradient_fill_survives_nan_gaps():
    x = np.linspace(0, 1, 50)
    y = np.sin(np.pi * x) + 0.1
    y[20:25] = np.nan
    fig, ax = ps.new_figure()
    ps.gradient_fill(ax, x, y, "#3D6FB6")
    ax.plot(x, y, color="#3D6FB6")
    ps.nice_limits(ax, np.nanmax(y))
    no_fail(ps.save(fig, "nan_gap", TMP / "out_misc"))


# ---------------------------------------------------------------- the checker

def _good_figure():
    fig, ax = ps.new_figure()
    ax.plot([0, 1], [0, 1], color="#3D6FB6", label="Li")
    ax.set_xlabel("Time (ps)")
    ax.set_ylabel("Energy (eV)")
    ps.place_legend(ax)
    return fig, ax


@test
def checker_passes_a_correct_figure():
    fig, _ = _good_figure()
    checks = ps.check_figure(fig)
    no_fail(checks)
    for topic in ("font", "text size", "text weight", "line width", "axes"):
        assert any(c.startswith(f"PASS {topic}") for c in checks), f"no PASS {topic} line"
    ps.plt.close(fig)


@test
def checker_catches_each_style_violation():
    def failing(mutate):
        fig, ax = _good_figure()
        mutate(ax)
        checks = ps.check_figure(fig)
        ps.plt.close(fig)
        return [c for c in checks if c.startswith("FAIL")]

    cases = {
        "FAIL font": lambda ax: ax.set_xlabel("t", fontfamily="DejaVu Sans"),
        "FAIL text size": lambda ax: ax.set_ylabel("E", fontsize=14),
        "FAIL text weight": lambda ax: ax.set_xlabel("t", fontweight="normal"),
        "FAIL line width": lambda ax: ax.plot([0, 1], [1, 0], lw=3.0),
        "FAIL axes": lambda ax: ax.grid(True),
    }
    for expected, mutate in cases.items():
        got = failing(mutate)
        assert any(g.startswith(expected) for g in got), f"{expected} not reported; got {got}"
    got = failing(lambda ax: ax.tick_params(direction="in"))
    assert any(g.startswith("FAIL axes") and "point in" in g for g in got), got
    got = failing(lambda ax: ax.spines["top"].set_visible(False))
    assert any(g.startswith("FAIL axes") and "hidden" in g for g in got), got
    got = failing(lambda ax: ax.tick_params(width=2.0))
    assert any(g.startswith("FAIL axes") and "width" in g for g in got), got
    got = failing(lambda ax: ax.text(0.5, 0.9, "note", fontsize=9))
    assert any(g.startswith("FAIL text size") for g in got), got
    # a legend made by hand instead of ps.place_legend is refused
    fig, ax = ps.new_figure()
    ax.plot([0, 1], [0, 1], color="#3D6FB6", label="Li")
    ax.legend(loc="lower right")
    got = [c for c in ps.check_figure(fig) if c.startswith("FAIL legend")]
    ps.plt.close(fig)
    assert got, "hand-made legend was not reported"


@test
def checker_covers_colorbar_and_top_axis():
    reg = fresh_registry()
    fig, ax = ps.new_figure(colorbar=True)
    im = ax.imshow(np.random.default_rng(0).random((20, 20)), extent=(0, 8, 0, 6), origin="lower")
    ax.set_xlabel(r"$x$ (Å)")
    ax.set_ylabel(r"$y$ (Å)")
    cb = ps.add_colorbar(fig, ax, im, r"$\rho$ (nm$^{\rm {-}3}$)")
    no_fail(ps.check_figure(fig))
    cb.ax.set_ylabel("bad", fontsize=12)                      # colorbar title in the wrong size
    assert any(c.startswith("FAIL text size") for c in ps.check_figure(fig))
    ps.plt.close(fig)

    fig, ax = ps.new_figure(top_axis=True)
    ax.plot([1, 2], [1, 2], color=reg.color("MD", "series"))
    top = ax.secondary_xaxis("top", functions=(lambda x: 1000 / np.maximum(x, 1e-6), lambda t: 1000 / np.maximum(t, 1e-6)))
    top.set_xlabel(r"$T$ (K)")
    no_fail(ps.check_figure(fig))
    top.set_xlabel(r"$T$ (K)", fontsize=12)
    assert any(c.startswith("FAIL text size") for c in ps.check_figure(fig))
    ps.plt.close(fig)


# ---------------------------------------------------------------- SVG

@test
def svg_embeds_the_font_subset():
    fig, ax = _good_figure()
    ax.set_xlabel(r"$E-E_{\rm VBM}$ (eV)")                    # italic math + upright text
    checks = ps.save(fig, "svgfont", TMP / "out_svg")
    assert any(c.startswith("PASS svg") for c in checks), checks
    text = (TMP / "out_svg" / "svgfont.svg").read_text(encoding="utf-8")
    ET.fromstring(text.encode("utf-8"))                       # still valid XML
    faces = re.findall(r"font-style:(\w+);font-weight:(\w+);src:url\(data:font/ttf;base64,", text)
    assert ("normal", "bold") in faces and ("italic", "bold") in faces, faces
    assert "<text" in text                                    # text stays editable text


# ---------------------------------------------------------------- init_figure.py and the template

INIT = SKILL / "scripts" / "init_figure.py"


def run_py(*args, cwd=None):
    return subprocess.run([sys.executable, *map(str, args)], capture_output=True, text=True, cwd=cwd)


@test
def init_figure_refuses_a_mistyped_project_path():
    ghost = TMP / "no" / "such" / "project"
    r = run_py(INIT, ghost, "DOS")
    assert r.returncode == 2 and "not found" in r.stdout, r.stdout + r.stderr
    assert not (TMP / "no").exists(), "a folder tree was created for a mistyped path"
    r = run_py(INIT, "--update-style", ghost)
    assert r.returncode == 2 and not (TMP / "no").exists()


@test
def init_figure_rejects_bad_names():
    proj = TMP / "names"
    proj.mkdir()
    for bad in ("001_DOS", "001", "has space", "ends.", "CON", "nul.txt", "中文"):
        r = run_py(INIT, proj, bad)
        assert r.returncode == 2, f"name {bad!r} was accepted"
    assert not (proj / "figures").exists(), "a rejected name still created folders"
    assert run_py(INIT, proj, "Li6PS5Cl_DOS").returncode == 0


@test
def template_is_guarded_then_runs_end_to_end():
    proj = TMP / "e2e"
    proj.mkdir()
    r = run_py(INIT, proj, "Demo_curve")
    assert r.returncode == 0, r.stdout + r.stderr
    folder = proj / "figures" / "001_Demo_curve"
    plot = folder / "plot.py"
    # 1. untouched template: stops with a clear message, no traceback
    r = run_py(plot, cwd=folder)
    assert r.returncode != 0 and "still the template" in (r.stdout + r.stderr), r.stdout + r.stderr
    assert "Traceback" not in r.stderr, r.stderr
    # 2. filled in: runs and produces every output without FAIL
    t = np.linspace(0, 10, 50)
    np.savetxt(folder / "data.dat", np.column_stack([t, t ** 0.5]), header="t  y")
    s = plot.read_text(encoding="utf-8")
    for old, new in (("__DATA_FILE__", "data.dat"), ("__X_MEANING__", "time (ps)"),
                     ("__Y_MEANING__", "signal (a.u.)"), ("__SERIES_KEY__", "Li"),
                     ("__SERIES_LABEL__", "Li"), ("__X_LABEL__", "Time (ps)"),
                     ("__Y_LABEL__", "Signal (a.u.)")):
        s = s.replace(old, new)
    plot.write_text(s, encoding="utf-8")
    r = run_py(plot, cwd=folder)
    assert r.returncode == 0, r.stdout + r.stderr
    name = folder.name
    for suffix in (".png", "_transparent.png", ".pdf", ".svg", ".tif", "_checks.txt"):
        assert (folder / f"{name}{suffix}").exists(), f"missing {name}{suffix}"
    assert "FAIL" not in (folder / f"{name}_checks.txt").read_text(encoding="utf-8")


@test
def update_style_replaces_an_old_copy():
    proj = TMP / "e2e"
    style = proj / "figures" / "_style" / "pubstyle.py"
    style.write_text('STYLE_VERSION = "0.7.0"\n', encoding="utf-8")
    r = run_py(INIT, "--update-style", proj)
    assert "UPDATED" in r.stdout, r.stdout
    assert re.search(r'^STYLE_VERSION = "0\.8\.0"', style.read_text(encoding="utf-8"), re.M)
    assert list((proj / "figures" / "_style" / "archive").glob("pubstyle_0.7.0_*.py"))


