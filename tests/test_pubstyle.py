def _good_figure():
    fig, ax = ps.new_figure()
    ax.plot([0, 1], [0, 1], color="#3D6FB6", label="Li")
    ax.set_xlabel("Time (ps)")
    ax.set_ylabel("Energy (eV)")
    ps.place_legend(ax)
    return fig, ax


@test
def checker_passes_a_correct_figure():
    fig, _ = _good_figure()
    checks = ps.check_figure(fig)
    no_fail(checks)
    for topic in ("font", "text size", "text weight", "line width", "axes"):
        assert any(c.startswith(f"PASS {topic}") for c in checks), f"no PASS {topic} line"
    ps.plt.close(fig)


@test
def checker_catches_each_style_violation():
    def failing(mutate):
        fig, ax = _good_figure()
        mutate(ax)
        checks = ps.check_figure(fig)
        ps.plt.close(fig)
        return [c for c in checks if c.startswith("FAIL")]

    cases = {
        "FAIL font": lambda ax: ax.set_xlabel("t", fontfamily="DejaVu Sans"),
        "FAIL text size": lambda ax: ax.set_ylabel("E", fontsize=14),
        "FAIL text weight": lambda ax: ax.set_xlabel("t", fontweight="normal"),
        "FAIL line width": lambda ax: ax.plot([0, 1], [1, 0], lw=3.0),
        "FAIL axes": lambda ax: ax.grid(True),
    }
    for expected, mutate in cases.items():
        got = failing(mutate)
        assert any(g.startswith(expected) for g in got), f"{expected} not reported; got {got}"
    got = failing(lambda ax: ax.tick_params(direction="in"))
    assert any(g.startswith("FAIL axes") and "point in" in g for g in got), got
    got = failing(lambda ax: ax.spines["top"].set_visible(False))
    assert any(g.startswith("FAIL axes") and "hidden" in g for g in got), got
    got = failing(lambda ax: ax.tick_params(width=2.0))
    assert any(g.startswith("FAIL axes") and "width" in g for g in got), got
    got = failing(lambda ax: ax.text(0.5, 0.9, "note", fontsize=9))
    assert any(g.startswith("FAIL text size") for g in got), got
    # a legend made by hand instead of ps.place_legend is refused
    fig, ax = ps.new_figure()
    ax.plot([0, 1], [0, 1], color="#3D6FB6", label="Li")
    ax.legend(loc="lower right")
    got = [c for c in ps.check_figure(fig) if c.startswith("FAIL legend")]
    ps.plt.close(fig)
    assert got, "hand-made legend was not reported"


